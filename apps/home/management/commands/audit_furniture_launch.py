"""Repeatable, local-only checks; never submit enquiries or send notifications."""
import json
from collections import Counter
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit

from django.conf import settings
from django.contrib.staticfiles import finders
from django.contrib.staticfiles.storage import staticfiles_storage
from django.core.files.storage import default_storage
from django.core.management.base import BaseCommand, CommandError
from django.db import connection, transaction
from django.db.migrations.executor import MigrationExecutor
from django.test import Client, override_settings
from django.urls import reverse

from apps.home.models import ClientShowcase, ContactSettings, EditablePage, TeamMember
from apps.home.templatetags.furniture_contacts import phone_link
from apps.products.models import Category, Product, ProductGalleryImage


class PageMarkup(HTMLParser):
    def __init__(self):
        super().__init__()
        self.ids, self.assets, self.links = [], set(), set()
        self.headings = 0

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if attrs.get('id'):
            self.ids.append(attrs['id'])
        if tag == 'h1':
            self.headings += 1
        if tag == 'a' and attrs.get('href'):
            self.links.add(attrs['href'])
        if tag in {'img', 'script', 'source'} and attrs.get('src'):
            self.assets.add(attrs['src'])
        if tag == 'link' and attrs.get('href'):
            if set(attrs.get('rel', '').split()) & {'stylesheet', 'icon', 'apple-touch-icon', 'manifest'}:
                self.assets.add(attrs['href'])
        for part in attrs.get('srcset', '').split(','):
            if part.strip():
                self.assets.add(part.strip().split()[0])


class Command(BaseCommand):
    help = 'Проверить страницы, доступ, ресурсы, публикацию и миграции без отправки заявок.'

    def add_arguments(self, parser):
        parser.add_argument('--output', help='Путь к JSON-отчёту (без контактов клиентов и секретов).')
        parser.add_argument('--deployment', action='store_true', help='Дополнительно проверить настройки HTTPS production.')
        parser.add_argument('--limit', type=int, default=20, help='Количество карточек изделий для проверки HTML (1–100).')

    def handle(self, *args, **options):
        if not 1 <= options['limit'] <= 100:
            raise CommandError('--limit должен быть от 1 до 100.')
        self.results = []
        self.deployment = options['deployment']
        executor = MigrationExecutor(connection)
        pending = executor.migration_plan(executor.loader.graph.leaf_nodes())
        self.add('migrations', 'error' if pending else 'ok',
                 f'Неприменённых миграций: {len(pending)}.')
        if options['deployment']:
            conditions = {
                'debug': not settings.DEBUG,
                'https': urlsplit(getattr(settings, 'SITE_URL', '')).scheme == 'https',
                'hosts': bool(settings.ALLOWED_HOSTS) and '*' not in settings.ALLOWED_HOSTS,
                'session_cookie': settings.SESSION_COOKIE_SECURE,
                'csrf_cookie': settings.CSRF_COOKIE_SECURE,
                'secret': len(settings.SECRET_KEY) >= 50 and len(set(settings.SECRET_KEY)) >= 5,
            }
            for name, valid in conditions.items():
                self.add('deployment.' + name, 'ok' if valid else 'error', 'Проверка настройки пройдена.' if valid else 'Проверьте production-настройку: ' + name + '.')
        if not pending:
            # GET can create sessions/thumbnail metadata. Roll back every DB write.
            # Thumbnail cache files may still be generated by normal rendering.
            with transaction.atomic(), override_settings(ALLOWED_HOSTS=['testserver']):
                self.check_data()
                self.check_pages(options['limit'])
                transaction.set_rollback(True)
        counts = Counter(row['status'] for row in self.results)
        report = {'version': 1, 'scope': 'local Django checks; no network, notifications or business writes',
                  'counts': dict(counts), 'checks': self.results}
        if options['output']:
            target = Path(options['output'])
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        for row in self.results:
            if row['status'] != 'ok':
                self.stdout.write(f"{row['status'].upper()} {row['check']}: {row['message']}")
        self.stdout.write(f"Проверок: {len(self.results)}; ошибок: {counts['error']}; замечаний: {counts['warning']}.")
        if counts['error']:
            raise CommandError('Проверка не пройдена. Исправьте ошибки из отчёта.')
        self.stdout.write(self.style.SUCCESS('Локальные проверки пройдены. Проверка рабочего сервера и браузера выполняется отдельно.'))

    def add(self, check, status, message):
        self.results.append({'check': check, 'status': status, 'message': message})

    def check_data(self):
        contacts = ContactSettings.objects.filter(pk=1, is_published=True).first()
        valid = contacts and any(phone_link(getattr(contacts, field)) for field in ('phone_primary', 'phone_secondary'))
        self.add('contacts', 'ok' if valid else 'error', 'Опубликован телефон мастерской.' if valid else 'Укажите и опубликуйте телефон в «Содержимое сайта → Контакты».')
        drafts = sum(row.draft != row.published for row in EditablePage.objects.all())
        self.add('drafts', 'warning' if drafts else 'ok', f'Неопубликованных черновиков: {drafts}.')
        products = Product.objects.filter(is_active=True)
        self.add('catalog', 'ok' if products.exists() else 'warning', f'Активных изделий: {products.count()}.')
        examples = products.filter(is_portfolio=True, badges__slug='example-for-discussion').distinct().count()
        self.add('portfolio.examples', 'error' if examples else 'ok', f'Примеров для обсуждения, ошибочно выбранных для портфолио: {examples}.')
        sources = [('products', products, ('image',)),
                   ('gallery', ProductGalleryImage.objects.filter(product__is_active=True), ('image',)),
                   ('categories', Category.objects.all(), ('image',)),
                   ('team', TeamMember.objects.filter(is_published=True), ('image',)),
                   ('clients', ClientShowcase.objects.filter(is_published=True), ('image',))]
        for label, rows, fields in sources:
            for row in rows:
                for field in fields:
                    image = getattr(row, field)
                    if image and not image.storage.exists(image.name):
                        self.add(f'media.{label}.{row.pk}.{field}', 'error', 'Исходное изображение отсутствует в хранилище.')
        for item in ClientShowcase.objects.filter(is_published=True, show_video_on_home=True):
            if not item.rutube_embed_url:
                self.add(f'video.{item.pk}', 'error', 'Включён показ видео, но ссылка Rutube отсутствует или некорректна.')

    def check_pages(self, limit):
        client = Client(raise_request_exception=False)
        names = ['home', 'catalog:catalog', 'furniture_services', 'furniture_kitchens',
                 'furniture_materials', 'furniture_reviews', 'furniture_about', 'furniture_contacts',
                 'furniture_portfolio', 'furniture_request', 'public_offer', 'privacy_policy', 'personal_data_consent']
        urls = [reverse(name) for name in names]
        urls += [product.get_absolute_url() for product in Product.objects.filter(is_active=True).order_by('pk')[:limit]]
        assets = set()
        for url in urls:
            response = client.get(url, secure=True)
            self.add('page.' + url, 'ok' if response.status_code == 200 else 'error', f'HTTP {response.status_code}.')
            if response.status_code != 200:
                continue
            markup = PageMarkup()
            markup.feed(response.content.decode(response.charset or 'utf-8'))
            duplicate_ids = sum(count > 1 for count in Counter(markup.ids).values())
            self.add('markup.' + url, 'ok' if markup.headings == 1 and not duplicate_ids else 'error',
                     f'H1: {markup.headings}; повторяющихся id: {duplicate_ids}.')
            assets.update(markup.assets)
            if url == reverse('home'):
                self.add('navigation.request', 'ok' if reverse('furniture_request') in markup.links else 'error', 'Ссылка на общую заявку в HTML главной.')
        for name in ['home:copy_list', 'home:contacts_manage', 'catalog:product_list_manage', 'appointments:order_list', 'appointments:callback_request_list']:
            response = client.get(reverse(name), secure=True)
            location = urlsplit(response.get('Location', '')).path
            valid = response.status_code == 302 and location in {reverse('users:login'), reverse('users:dashboard')}
            self.add('access.' + name, 'ok' if valid else 'error', f'Гостевой доступ: HTTP {response.status_code}.')
        for url in ['/calculator/', '/size-helper/']:
            response = client.get(url, secure=True)
            self.add('legacy.' + url, 'ok' if response.status_code == 404 else 'error', f'HTTP {response.status_code}.')
        for url in ['/robots.txt', '/sitemap.xml', '/sitemap-pages.xml', '/favicon.ico', '/apple-touch-icon.png']:
            response = client.get(url, secure=True)
            valid = response.status_code == 200
            if url in {'/favicon.ico', '/apple-touch-icon.png'} and response.status_code == 301:
                target = response.get('Location', '')
                valid = urlsplit(target).path.startswith(urlsplit(settings.STATIC_URL).path)
                if valid:
                    assets.add(target)
            self.add('resource.' + url, 'ok' if valid else 'error', f'HTTP {response.status_code}.')
        for url in sorted(assets):
            path = urlsplit(url).path
            static_prefix = urlsplit(settings.STATIC_URL).path
            media_prefix = urlsplit(settings.MEDIA_URL).path
            if static_prefix and path.startswith(static_prefix):
                name = unquote(path[len(static_prefix):])
                exists = staticfiles_storage.exists(name) if self.deployment else bool(finders.find(name)) or staticfiles_storage.exists(name)
            elif media_prefix and path.startswith(media_prefix):
                exists = default_storage.exists(unquote(path[len(media_prefix):]))
            else:
                continue
            self.add('asset.' + path, 'ok' if exists else 'error', 'Ресурс найден.' if exists else 'Ресурс отсутствует.')
